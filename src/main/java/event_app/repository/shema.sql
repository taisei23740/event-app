CREATE TABLE users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50),
    age INTEGER,
    email VARCHAR(255) UNIQUE,
    password VARCHAR(255)
);

CREATE TABLE event (
    event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name VARCHAR(50),
    capacity INTEGER CHECK (capacity >= 1),
    event_datetime TIMESTAMP,
    location VARCHAR(255),
    organizer_id INTEGER REFERENCES users(user_id),
    registration_datetime TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE event_application (
    application_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES event(event_id),
    user_id INTEGER NOT NULL REFERENCES users(user_id),
    application_datetime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (event_id, user_id)
);
